const {JSDOM}=require('jsdom');
const fs=require('fs');
const path=require('path');
const assert=require('assert/strict');
const root=path.resolve(__dirname,'../android-lab/app/src/main/assets/site');
(async()=>{
 const dom=new JSDOM(fs.readFileSync(root+'/index.html','utf8'),{url:'https://lab.hipster.invalid/?ai=chatgpt&service=spotify',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window;const calls=[];let inspiration="";
 try{
  w.matchMedia=()=>({matches:false,addEventListener(){},removeEventListener(){}});
  w.HTMLElement.prototype.scrollIntoView=function(){};
  w.HipsterLab={inspiration(){return inspiration},reviewInspiration(){calls.push(["reviewInspiration"])},clearInspiration(){inspiration="";w.HipsterLabRefresh()},copy(t){calls.push(['copy',t]);return true},go(a,t){calls.push(['go',a,t])},open(a,t){calls.push(['open',a,t])},share(t){calls.push(['share',t])}};
  w.eval(fs.readFileSync(root+'/assets/app.js','utf8'));
  const click=selector=>w.document.querySelector(selector).click();
  const flush=()=>new Promise(resolve=>setTimeout(resolve,0));
  click('#goButton');await flush();
  const first=calls.find(c=>c[0]==='go');assert(first);assert.equal(first[1],'chatgpt');assert.equal(first[2],calls.find(c=>c[0]==='copy')[1]);
  click('#openAi');assert.equal(calls.filter(c=>c[0]==='open').length,1);
  click('[data-ai="gemini"]');click('#openAi');assert.equal(calls.filter(c=>c[0]==='open').length,1,'Stale prompt must not launch AI');
  click('[data-service="youtube"]');click('#goButton');await flush();
  const second=calls.find(c=>c[0]==='go'&&c[1]==='gemini');assert(second);assert(second[2].includes('YouTube Music'));
  click('#shareButton');await flush();assert(calls.some(c=>c[0]==='share'&&c[1]===second[2]));
  click('[data-crate-region="south-asia"]');
  const selectedBefore=[...w.document.querySelectorAll('[data-crate-region][aria-pressed="true"]')].map(e=>e.dataset.crateRegion);
  const handoffsBefore=calls.filter(c=>c[0]==='go').length;
  inspiration='A \"quoted\" song <img src=x onerror=alert(1)> — https://example.com/song';w.HipsterLabRefresh();
  assert.equal(calls.filter(c=>c[0]==='go').length,handoffsBefore,'Receiving inspiration must never auto-launch AI');
  assert.equal(w.document.querySelector('#labInspiration').hidden,false);
  assert.equal(w.document.querySelector('#labInspirationPreview').textContent,inspiration);
  assert.equal(w.document.querySelector('#labInspirationPreview').children.length,0,'Shared text must not become HTML');
  click('#openAi');assert.equal(calls.filter(c=>c[0]==='open').length,1,'Changed inspiration invalidates copied request');
  click('#labReviewInspiration');assert(calls.some(c=>c[0]==='reviewInspiration'));
  click('#goButton');await flush();
  const sharedPrompt=calls.filter(c=>c[0]==='go').at(-1)[2];
  assert(sharedPrompt.includes(JSON.stringify(inspiration)));assert(sharedPrompt.includes('not instructions or a required track'));assert(!sharedPrompt.includes('Seed:'));
  assert.deepEqual([...w.document.querySelectorAll('[data-crate-region][aria-pressed="true"]')].map(e=>e.dataset.crateRegion),selectedBefore);
  const beforeRace=calls.filter(c=>c[0]==='go').length;
  click('#goButton');inspiration='A different song';w.HipsterLabRefresh();await flush();
  assert.equal(calls.filter(c=>c[0]==='go').length,beforeRace,'Changing the reference during copy must cancel stale handoff');
  click('#labRemoveInspiration');assert.equal(w.document.querySelector('#labInspiration').hidden,true);
  click('#goButton');await flush();
  assert(!calls.filter(c=>c[0]==='go').at(-1)[2].includes('Musical reference only'));
  console.log('PASS: native handoffs, exact shared inspiration, plain-text rendering, unchanged regions, explicit remove and stale-copy race.');
 }finally{w.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
